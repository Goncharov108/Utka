import AppKit

struct ClipItem: Codable, Equatable {
    var id: String
    var text: String
    /// Когда скопировано. В старом clipboard.json поля нет.
    var copiedAt: Date?
}

/// Настройки истории буфера. Все ключи UserDefaults буфера — только здесь.
struct ClipboardPrefs {
    /// В чём считается срок хранения.
    enum Unit: Int, CaseIterable {
        case minutes, hours, days

        /// Подпись в выборе единицы.
        var title: String {
            switch self {
            case .minutes: return "минут"
            case .hours: return "часов"
            case .days: return "дней"
            }
        }

        /// Секунд в одной единице.
        var seconds: TimeInterval {
            switch self {
            case .minutes: return 60
            case .hours: return 3_600
            case .days: return 86_400
            }
        }
    }

    /// Ключи UserDefaults буфера.
    private enum Key: String {
        case remember = "clipboardRemember"
        case skipSecrets = "clipboardSkipSecrets"
        case expires = "clipboardExpires"
        case ageCount = "clipboardAgeCount"
        case ageUnit = "clipboardAgeUnit"
        case clearOnReboot = "clipboardClearOnReboot"
        case confirmClear = "clipboardConfirmClear"
        case bootTime = "clipboardBootTime"
    }

    /// Допустимое число единиц срока.
    static let ageRange = 1...999

    /// Где лежат настройки. У самопроверки — свой отдельный набор.
    let defaults: UserDefaults

    init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
    }

    /// «Запоминать скопированное». Без ключа — да.
    var remember: Bool {
        get { flag(.remember, fallback: true) }
        nonmutating set { store(newValue, .remember) }
    }

    /// «Не сохранять пароли». Без ключа — да.
    var skipSecrets: Bool {
        get { flag(.skipSecrets, fallback: true) }
        nonmutating set { store(newValue, .skipSecrets) }
    }

    /// «Удалять записи старше». Без ключа — да.
    var expires: Bool {
        get { flag(.expires, fallback: true) }
        nonmutating set { store(newValue, .expires) }
    }

    /// Сколько единиц живёт запись. Без ключа — 7. Число вне 1–999 не сохраняется.
    var ageCount: Int {
        get {
            let stored = defaults.integer(forKey: Key.ageCount.rawValue)
            return Self.ageRange.contains(stored) ? stored : 7
        }
        nonmutating set {
            guard Self.ageRange.contains(newValue) else { return }
            store(newValue, .ageCount)
        }
    }

    /// Единица срока. Без ключа — дни.
    var ageUnit: Unit {
        get { (defaults.object(forKey: Key.ageUnit.rawValue) as? Int).flatMap(Unit.init(rawValue:)) ?? .days }
        nonmutating set { store(newValue.rawValue, .ageUnit) }
    }

    /// «Чистить после перезагрузки Мака». Без ключа — нет.
    var clearOnReboot: Bool {
        get { flag(.clearOnReboot, fallback: false) }
        nonmutating set { store(newValue, .clearOnReboot) }
    }

    /// «Спрашивать перед очисткой». Без ключа — да.
    var confirmClear: Bool {
        get { flag(.confirmClear, fallback: true) }
        nonmutating set { store(newValue, .confirmClear) }
    }

    /// Время загрузки системы, которое застал прошлый запуск утки.
    var bootTime: Double? {
        get { defaults.object(forKey: Key.bootTime.rawValue) as? Double }
        nonmutating set { store(newValue, .bootTime) }
    }

    /// Сколько секунд живёт запись. nil — срок выключен.
    var lifetime: TimeInterval? {
        expires ? TimeInterval(ageCount) * ageUnit.seconds : nil
    }

    /// Флажок, а пока ключа нет — значение по умолчанию.
    private func flag(_ key: Key, fallback: Bool) -> Bool {
        defaults.object(forKey: key.rawValue) as? Bool ?? fallback
    }

    /// Пишет значение. nil стирает ключ.
    private func store(_ value: Any?, _ key: Key) {
        defaults.set(value, forKey: key.rawValue)
    }
}

/// История скопированного текста. Картинки и файлы сюда не попадают.
final class ClipboardHistory {
    /// Пометки временного: программа просит не запоминать. Не записываются никогда.
    static let transientTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    /// Пометки паролей и менеджеров паролей. Не записываются при «Не сохранять пароли».
    static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]
    /// Текст длиннее этого в историю не попадает.
    static let textLimit = 100_000

    private(set) var items: [ClipItem] = []
    var onChange: (() -> Void)?
    /// Настройки, по которым живёт эта история.
    let prefs: ClipboardPrefs

    private let storeURL: URL
    private var lastCount: Int
    private var bypass = false
    private var timer: Timer?
    /// Таймер опрашивает буфер. Без запоминания он тикает раз в минуту только ради срока записей.
    private var polling = false
    /// Когда последний раз снимали записи старше срока.
    private var lastSweep = Date.distantPast
    /// Срок записей проверяется не чаще этого.
    private static let sweepPeriod: TimeInterval = 60

    init(storeURL: URL, prefs: ClipboardPrefs = ClipboardPrefs()) {
        self.storeURL = storeURL
        self.prefs = prefs
        lastCount = NSPasteboard.general.changeCount
        load()
    }

    /// Запуск утки: чистка после перезагрузки, записи старше срока, затем опрос буфера, если запоминание включено.
    func start() {
        guard timer == nil else { return }
        if let boot = Self.systemBootTime() { noteBoot(boot) }
        dropExpired()
        polling = prefs.remember
        if polling { captureCurrentIfNeeded() }
        restartTimer()
    }

    /// Настройки буфера поменяли. Включённое запоминание не берёт то, что уже лежит в буфере. Новый срок применяется сразу.
    func applyPrefs() {
        if timer != nil, prefs.remember != polling {
            polling = prefs.remember
            lastCount = NSPasteboard.general.changeCount
            restartTimer()
        }
        if sweep(now: Date()) { save() }
        onChange?()
    }

    /// Снимает записи старше срока, свежие оставляет.
    func dropExpired(now: Date = Date()) {
        guard sweep(now: now) else { return }
        save()
        onChange?()
    }

    /// Сверяет время загрузки системы с прошлым запуском и запоминает нынешнее. После перезагрузки чистит историю, если так настроено.
    func noteBoot(_ bootTime: Double) {
        if prefs.clearOnReboot, Self.rebooted(saved: prefs.bootTime, current: bootTime) {
            clear()
        }
        prefs.bootTime = bootTime
    }

    /// Мак перезагружался: время загрузки сменилось. Сдвиг до минуты — та же загрузка: macOS сдвигает это время, когда подводит часы.
    static func rebooted(saved: Double?, current: Double) -> Bool {
        guard let saved else { return false }
        return abs(current - saved) > 60
    }

    /// Время загрузки системы из kern.boottime, секунды с 1970 года.
    static func systemBootTime() -> Double? {
        var boot = timeval()
        var size = MemoryLayout<timeval>.size
        guard sysctlbyname("kern.boottime", &boot, &size, nil, 0) == 0 else { return nil }
        return Double(boot.tv_sec) + Double(boot.tv_usec) / 1_000_000
    }

    /// Кладёт текст обратно в буфер и не записывает это в историю.
    func copyToPasteboard(_ text: String) {
        bypass = true
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastCount = pb.changeCount
        bypass = false
    }

    func remove(id: String) {
        items.removeAll { $0.id == id }
        save()
        onChange?()
    }

    /// Снимает все строки истории. Системный буфер не трогает.
    func clear() {
        guard !items.isEmpty else { return }
        items = []
        save()
        onChange?()
    }

    /// Записывать ли в историю. Файл, временное и длинное — никогда, скрытое — если пароли не сохранять.
    static func accepts(types: [String], text: String, skipSecrets: Bool) -> Bool {
        let marks = Set(types)
        guard !marks.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              marks.isDisjoint(with: transientTypes),
              !skipSecrets || marks.isDisjoint(with: secretTypes) else { return false }
        return text.count <= textLimit
    }

    /// Правило истории: пустое, повтор подряд и то, что не пропустил `accepts`, не добавляются.
    /// `date` — время копирования; заодно уходят записи, которые к нему старше срока.
    func consider(text: String?, types: [String] = [], at date: Date = Date()) {
        guard let text, Self.accepts(types: types, text: text, skipSecrets: prefs.skipSecrets) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        if items.first?.text == trimmed { return }
        items.insert(ClipItem(id: UUID().uuidString, text: trimmed, copiedAt: date), at: 0)
        if items.count > 50 {
            items.removeLast(items.count - 50)
        }
        _ = sweep(now: date)
        save()
        onChange?()
    }

    /// Убирает из списка записи старше срока и говорит, убрал ли что-то. Сохраняет вызывающий.
    private func sweep(now: Date) -> Bool {
        lastSweep = now
        guard let lifetime = prefs.lifetime else { return false }
        let before = items.count
        items.removeAll { item in
            guard let copiedAt = item.copiedAt else { return false }
            return now.timeIntervalSince(copiedAt) > lifetime
        }
        return items.count != before
    }

    /// Опрос буфера, пока запоминание включено. Иначе тот же таймер раз в минуту.
    private func restartTimer() {
        timer?.invalidate()
        let timer = Timer(timeInterval: polling ? 0.3 : Self.sweepPeriod, repeats: true) { [weak self] _ in
            self?.tick()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Такт: буфер — каждый раз, срок записей — не чаще раза в минуту.
    private func tick() {
        guard polling else {
            dropExpired()
            return
        }
        poll()
        let now = Date()
        guard now.timeIntervalSince(lastSweep) >= Self.sweepPeriod else { return }
        dropExpired(now: now)
    }

    /// Текст и пометки системного буфера — на правило истории.
    private func readPasteboard() {
        let pb = NSPasteboard.general
        consider(text: pb.string(forType: .string), types: pb.types?.map(\.rawValue) ?? [])
    }

    private func captureCurrentIfNeeded() {
        readPasteboard()
        lastCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let count = NSPasteboard.general.changeCount
        guard count != lastCount else { return }
        lastCount = count
        if bypass { return }
        readPasteboard()
    }

    /// Записям старого файла без времени ставит нынешнее и сразу сохраняет: срок пойдёт с этого запуска.
    private func load() {
        guard let data = try? Data(contentsOf: storeURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
        if items.count > 50 { items = Array(items.prefix(50)) }
        guard items.contains(where: { $0.copiedAt == nil }) else { return }
        let now = Date()
        for index in items.indices where items[index].copiedAt == nil {
            items[index].copiedAt = now
        }
        save()
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: storeURL, options: .atomic)
    }
}

/// Список истории буфера.
final class ClipboardView: NSView {
    /// Держит островок открытым, пока на экране вопрос об очистке.
    var onDrag: ((Bool) -> Void)?

    private let scroll = NSScrollView()
    private let document = FlippedView()
    private let empty = UtkaChrome.label("Пока пусто", size: 13, color: UtkaChrome.dim)
    private let clearButton = NSButton()
    private var rows: [TextRowView] = []
    private let history: ClipboardHistory
    /// Вопрос «Очистить всю историю?», пока он на экране.
    private var clearPrompt: RemovePrompt?

    init(history: ClipboardHistory) {
        self.history = history
        super.init(frame: .zero)
        wantsLayer = true
        let clip = FlippedClipView()
        scroll.contentView = clip
        scroll.documentView = document
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.autohidesScrollers = true
        empty.alignment = .center
        clearButton.isBordered = false
        clearButton.target = self
        clearButton.action = #selector(clearTapped)
        clearButton.setButtonType(.momentaryPushIn)
        paintClear()
        addSubview(scroll)
        addSubview(empty)
        addSubview(clearButton)
        history.onChange = { [weak self] in self?.rebuild() }
        NotificationCenter.default.addObserver(forName: IslandLook.changed, object: nil, queue: .main) { [weak self] _ in
            self?.empty.textColor = UtkaChrome.dim
            self?.paintClear()
        }
        rebuild()
    }

    required init?(coder: NSCoder) { nil }

    override func resizeSubviews(withOldSize oldSize: NSSize) {
        super.resizeSubviews(withOldSize: oldSize)
        placeChrome()
        layoutRows()
    }

    /// Кнопка справа сверху, список под ней. Пустой буфер — только подпись вместо списка.
    private func placeChrome() {
        let showClear = !rows.isEmpty
        clearButton.isHidden = !showClear
        guard showClear else {
            scroll.frame = bounds
            empty.frame = bounds
            return
        }
        let bar: CGFloat = 22
        let buttonW: CGFloat = 78
        clearButton.frame = NSRect(x: bounds.width - buttonW, y: bounds.height - bar, width: buttonW, height: bar)
        let list = NSRect(x: 0, y: 0, width: bounds.width, height: max(0, bounds.height - bar - 4))
        scroll.frame = list
        empty.frame = list
    }

    /// Подпись кнопки в цвете хрома.
    private func paintClear() {
        clearButton.attributedTitle = NSAttributedString(
            string: "Очистить",
            attributes: [
                .font: UtkaChrome.font(12, weight: .medium),
                .foregroundColor: UtkaChrome.dim
            ]
        )
    }

    @objc private func clearTapped() {
        guard history.prefs.confirmClear else {
            history.clear()
            return
        }
        askClear()
    }

    /// Спрашивает и только потом чистит. Пока окно открыто, островок не закрывается.
    private func askClear() {
        guard clearPrompt == nil else { return }
        let prompt = RemovePrompt(text: "Очистить всю историю буфера? Системный буфер не изменится.")
        clearPrompt = prompt
        prompt.onChoose = { [weak self] drop in
            self?.clearPrompt = nil
            self?.onDrag?(false)
            guard drop else { return }
            self?.history.clear()
        }
        onDrag?(true)
        DispatchQueue.main.async { [weak self] in
            prompt.show(over: self?.window)
        }
    }

    private func rebuild() {
        document.subviews.forEach { $0.removeFromSuperview() }
        rows = history.items.map { item in
            let row = TextRowView()
            row.show(title: oneLine(item.text), detail: "")
            row.toolTip = String(item.text.prefix(500))
            row.onClick = { [weak self] in self?.history.copyToPasteboard(item.text) }
            row.onDelete = { [weak self] in self?.history.remove(id: item.id) }
            document.addSubview(row)
            return row
        }
        empty.stringValue = history.prefs.remember ? "Пока пусто" : "Запоминание выключено в настройках"
        empty.isHidden = !rows.isEmpty
        placeChrome()
        layoutRows()
    }

    private func layoutRows() {
        let width = max(scroll.contentView.bounds.width, bounds.width)
        var y: CGFloat = 0
        for row in rows {
            row.frame = NSRect(x: 0, y: y, width: width, height: 40)
            y += 46
        }
        document.frame = NSRect(x: 0, y: 0, width: width, height: max(y, scroll.contentView.bounds.height))
    }
}
